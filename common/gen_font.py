#!/usr/bin/env python3
"""Render ASCII 32..126 from a monospace font into an 8x16 1-bpp bitmap font header.
usage: gen_font.py [font_path] [size] > font8x16.h   (MSB = leftmost pixel)"""
import sys
from PIL import Image, ImageDraw, ImageFont

path = sys.argv[1] if len(sys.argv) > 1 else "/System/Library/Fonts/Monaco.ttf"
size = float(sys.argv[2]) if len(sys.argv) > 2 else 13
W, H, BASE, THRESH = 8, 16, 12, 100
font = ImageFont.truetype(path, size)
adv = font.getlength("M")
x_off = (W - adv) / 2.0

rows_out = []
for code in range(32, 127):
    img = Image.new("L", (W, H), 0)
    ImageDraw.Draw(img).text((x_off, BASE), chr(code), font=font, fill=255, anchor="ls")
    glyph = []
    for y in range(H):
        b = 0
        for x in range(W):
            if img.getpixel((x, y)) >= THRESH:
                b |= 0x80 >> x
        glyph.append(b)
    rows_out.append((code, glyph))

if "--preview" in sys.argv:
    for code, g in rows_out:
        if chr(code) in "AaQg@%&{":
            print(repr(chr(code)))
            for b in g:
                print("".join("#" if b & (0x80 >> x) else "." for x in range(W)))
    sys.exit(0)

print("// Generated by gen_font.py from %s @ %g. ASCII 32..126, 8x16, MSB = leftmost pixel." % (path.split("/")[-1], size))
print("#ifndef FONT8X16_H\n#define FONT8X16_H\n#include <stdint.h>\n")
print("static const uint8_t font8x16[95][16] = {")
for code, g in rows_out:
    label = chr(code) if chr(code) not in "\\*/" else "'%s'" % chr(code)
    print("    {%s}, /* %3d %s */" % (",".join("0x%02X" % b for b in g), code, label))
print("};\n\n#endif")
